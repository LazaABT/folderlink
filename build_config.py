"""Generates config.js from .env. Run this after changing .env, then publish config.js."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def read_env(path):
    values = {}
    if not path.exists():
        return values
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, value = line.split("=", 1)
        values[key.strip()] = value.strip().strip("'\"")
    return values


def build_config(env):
    config = {}

    if env.get("PEER_HOST"):
        peer = {
            "host": env["PEER_HOST"],
            "port": int(env.get("PEER_PORT") or 443),
            "path": env.get("PEER_PATH") or "/",
            "secure": True,
        }
        if env.get("PEER_KEY"):
            peer["key"] = env["PEER_KEY"]
        config["peer"] = peer

    if env.get("STUN_URL") or env.get("TURN_URL"):
        servers = [{"urls": env.get("STUN_URL") or "stun:stun.l.google.com:19302"}]
        if env.get("TURN_URL"):
            servers.append({
                "urls": env["TURN_URL"],
                "username": env.get("TURN_USERNAME", ""),
                "credential": env.get("TURN_CREDENTIAL", ""),
            })
        config["iceServers"] = servers

    return config


def main():
    config = build_config(read_env(ROOT / ".env"))
    body = json.dumps(config, indent=2).replace("<", "\\u003c")
    text = "// Generated by build_config.py from .env. This file is public once published.\n"
    text += f"window.FOLDERLINK_CONFIG = {body};\n"
    (ROOT / "config.js").write_text(text, encoding="utf-8")
    print("Wrote config.js:", "default settings" if not config else ", ".join(config))


if __name__ == "__main__":
    main()
